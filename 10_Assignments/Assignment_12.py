# Convert the string "hello world" to uppercase and "PYTHON" to lowercase.

print("hello world".upper())
print("PYTHON".lower())


# Count how many times the letter "a" appears in the 
# string `"bananarama"` using a string method.

s = "bananarama"
print("Count of 'a':", s.count("a"))


# Format the float number pi = 3.14159265 to display 
# only 2 decimal places inside an f-string.

pi = 3.14159265
print(f"Pi rounded: {pi:.2f}")


# Given text = "I like apples and apple pie", 
# replace all occurrences of "apple" with "orange" and print the result.

text = "I like apples and apple pie"
print(text.replace("apple", "orange"))