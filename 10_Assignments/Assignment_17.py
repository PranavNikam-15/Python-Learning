# Write a lambda function that squares a given number. 

square = lambda x: x ** 2

print("Square of 15:", square(15))
print("Square of 25:", square(25))



# Write a lambda function that checks if a number is greater than 10.

is_greater = lambda x: x > 10

print("Is 8 > 10?", is_greater(8))
print("Is 14 > 10?", is_greater(14))